#!/usr/bin/env python3
"""
mk_nccl_fixture.py — regenerate the FIXTURE nccl-tests logs under
  fixtures/FIXTURE_NOT_REAL_DATA/nccl/

*** THESE ARE NOT REAL CLUSTER RESULTS. ***
There are no NCCL runs on IREN_MKZ yet (no route to the compute plane). These
files exist ONLY to prove the nccl_ingest.py parser end to end. Every line of the
emitted format is copied from a real producer in this deployment:

  * preamble + round banners  -> nvis-rack-status-v3/bin/scripts/nccl_allreduce.sbatch:145-176
  * 13-col / 11-col headers   -> llmb IREN_MKZ8k_llmbrun/tests/fixtures/mk_nccl_logs.sh
                                 and lib/llmb.sh:240-245 (the dialect comment)
  * `# Using devices` block   -> nccl-tests upstream banner
  * footers                   -> `# Out of bounds values` / `# Avg bus bandwidth`
  * sweep -b 512M -e 8G -f 2  -> GB300_B300_Validation_MOP.md §7.3 step 1
  * bandwidth magnitudes      -> MOP §7.3 scope C "reference good range" 720-810 GB/s
                                 (rack / NVLink domain) and scope-appropriate
                                 all_gather values vs conf/profiles/gb300-nvl72.conf

Numbers are DETERMINISTIC and internally consistent (busbw = algbw * 2(n-1)/n for
all_reduce, algbw*(n-1)/n for all_gather, time = size/algbw) so the parser's output
can be checked arithmetically rather than against a magic constant.

Every file carries the FIXTURE_NOT_REAL_DATA banner, which nccl_parse.py detects
and which forces fixture=true / source='fixture' in the Parquet rows regardless of
what flags the caller passes.
"""
from __future__ import annotations

import os
import sys

BANNER = ("# ################ FIXTURE_NOT_REAL_DATA — SYNTHETIC NCCL OUTPUT ################\n"
          "# Generated by datalake/fixtures/mk_nccl_fixture.py to exercise nccl_ingest.py.\n"
          "# This is NOT a real IREN_MKZ run. Rows parsed from it are tagged\n"
          "# source='fixture', fixture=true, and land under run_id=FIXTURE-*.\n"
          "# ##############################################################################\n")

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "FIXTURE_NOT_REAL_DATA", "nccl")

# 18 trays x 4 GB300 GPUs = 72 ranks — PROFILE_NODES_PER_RACK=18,
# PROFILE_GPUS_PER_NODE=4 from conf/profiles/gb300-nvl72.conf
NODES = [f"example50-dh01-h01-{i:02d}" for i in range(1, 19)]
GPUS_PER_NODE = 4
NRANKS = len(NODES) * GPUS_PER_NODE

# MOP §7.3: all_reduce_perf_mpi -b 512M -e 8G -f 2
SIZES = [512 * 1024**2, 1024**3, 2 * 1024**3, 4 * 1024**3, 8 * 1024**3]


def using_devices_block() -> str:
    out = ["#", "# Using devices"]
    rank = 0
    pid = 1837400
    for n_i, host in enumerate(NODES):
        for dev in range(GPUS_PER_NODE):
            out.append(f"#  Rank {rank:3d} Group  0 Pid {pid + rank:7d} on {host} "
                       f"device {dev:2d} [0x{0x1b + dev * 0x20:02x}] NVIDIA GB300")
            rank += 1
    out.append("#")
    return "\n".join(out) + "\n"


def sweep_rows(busbw_targets, factor, cols=13, dtype="float", redop="sum",
               root=-1, validation=True):
    """Emit nccl-tests data rows. busbw = algbw * factor, time = size/algbw."""
    lines = []
    for size, oop_bw in zip(SIZES, busbw_targets):
        count = size // 4                     # float = 4 B
        ip_bw = round(oop_bw * 1.0031, 2)     # in-place is marginally faster
        o_alg = round(oop_bw / factor, 2)
        i_alg = round(ip_bw / factor, 2)
        o_us = round(size / (o_alg * 1000.0), 1)
        i_us = round(size / (i_alg * 1000.0), 1)
        wrong = "     0" if validation else "   N/A"
        if cols == 13:
            lines.append(f"{size:12d} {count:12d}  {dtype:>8s} {redop:>7s} {root:>7d}  "
                         f"{o_us:7.1f} {o_alg:7.2f} {oop_bw:7.2f} {wrong}  "
                         f"{i_us:7.1f} {i_alg:7.2f} {ip_bw:7.2f} {wrong}")
        else:
            lines.append(f"{size:12d} {count:12d}  {dtype:>8s}  "
                         f"{o_us:7.1f} {o_alg:7.2f} {oop_bw:7.2f} {wrong}  "
                         f"{i_us:7.1f} {i_alg:7.2f} {ip_bw:7.2f} {wrong}")
    return lines


HDR13 = (
    "#                                                              out-of-place                       in-place\n"
    "#       size         count      type   redop    root     time   algbw   busbw #wrong     time   algbw   busbw #wrong\n"
    "#        (B)    (elements)                             (us)  (GB/s)  (GB/s)  (rank)     (us)  (GB/s)  (GB/s)  (rank)\n"
)
HDR11 = (
    "#                                                     out-of-place                       in-place\n"
    "#       size         count      type     time   algbw   busbw #wrong     time   algbw   busbw #wrong\n"
    "#        (B)    (elements)             (us)  (GB/s)  (GB/s)  (rank)     (us)  (GB/s)  (GB/s)  (rank)\n"
)


def nthread_banner(validation=1):
    return (f"# nThread 1 nGpus 1 minBytes {SIZES[0]} maxBytes {SIZES[-1]} step: 2(factor) "
            f"warmup iters: 5 iters: 20 agg iters: 1 validation: {validation} graph: 0\n")


def file_a() -> tuple[str, str]:
    """
    rack-status direct-mpirun path (the one actually used on IREN_MKZ):
      bin/scripts/run_nccl_mpi.sh -> nccl_allreduce.sbatch, 2 rounds, 13-col all_reduce.
    Filename shape: <user>-NCCL-1Rack-<rack>-<N>N-<jobid>.txt
    """
    # all_reduce bus factor = 2(n-1)/n
    f = 2.0 * (NRANKS - 1) / NRANKS
    r1 = [731.44, 768.03, 789.55, 798.21, 803.96]   # MOP §7.3 C observed 720-810
    r2 = [728.90, 765.11, 786.42, 795.60, 801.33]   # round 2, within ±5% of round 1
    b = [BANNER]
    b.append("nccl_allreduce: nodes=18 np=72 gpus/node=4 sizes=512M..8G rounds=2\n")
    b.append("nccl_allreduce: NCCL version=2.30.7 lib=/opt/nvis/nccl/2.30.7/lib/libnccl.so.2\n")
    b.append("nccl_allreduce: bin=/opt/nvis/nccl-tests/build/all_reduce_perf "
             "per-collective timeout=120s (nccl-tests -T)\n")
    b.append("nccl_allreduce: NCCL_IB_HCA=mlx5_0,mlx5_3,mlx5_4,mlx5_5 "
             "NCCL_SOCKET_IFNAME=enp1s0f0np0 (MPI bootstrap: ob1/tcp over enp1s0f0np0)\n")
    for rnd, vals in ((1, r1), (2, r2)):
        b.append(f"===== nccl_allreduce round {rnd}/2 =====\n")
        b.append(nthread_banner())
        b.append(using_devices_block())
        b.append(HDR13)
        b.append("\n".join(sweep_rows(vals, f, cols=13)) + "\n")
        b.append("# Out of bounds values : 0 OK\n")
        b.append(f"# Avg bus bandwidth    : {sum(vals) / len(vals):.2f}\n")
        b.append("#\n")
        b.append(f"nccl_allreduce: round {rnd}/2 OK\n")
    b.append("nccl_allreduce: exit 0\n")
    b.append(BANNER)
    return "FIXTURE-nvis-NCCL-1Rack-h01r01-18N-999001.txt", "".join(b)


def file_b() -> tuple[str, str]:
    """
    llmb-run microbenchmark_nccl sweep file: 11-COLUMN dialect (all_gather has no
    redop/root) AND `validation: 0` so `#wrong` is N/A. This is the case that a
    hardcoded $8 parser reports as 0.00 GB/s — see lib/llmb.sh:240-245.
    Filename shape: nccl_LOG_<collective>_<gpus>_iter1.txt
    """
    f = (NRANKS - 1) / NRANKS                       # all_gather bus factor
    vals = [641.20, 663.87, 678.44, 685.02, 689.13]  # > profile floor 620
    b = [BANNER]
    b.append("# Collective test starting: all_gather_perf_mpi\n")
    b.append(nthread_banner(validation=0))
    b.append(using_devices_block())
    b.append(HDR11)
    b.append("\n".join(sweep_rows(vals, f, cols=11, validation=False)) + "\n")
    b.append("# Out of bounds values : 0 OK\n")
    b.append(f"# Avg bus bandwidth    : {sum(vals) / len(vals):.2f}\n")
    b.append("# Collective test concluded: all_gather_perf_mpi\n")
    b.append(BANNER)
    return "nccl_LOG_all_gather_72_iter1.txt", "".join(b)


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "README_FIXTURE.md"), "w") as fh:
        fh.write(__doc__.lstrip())
    for name, body in (file_a(), file_b()):
        p = os.path.join(OUT, name)
        with open(p, "w") as fh:
            fh.write(body)
        print(f"wrote {p} ({len(body)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
